section = """## Сетка как якоря: один темп — частный случай (шаг 1 из 4)

Задача про треки, где темп меняется посреди композиции (резко или плавно). Первый шаг — модель, без
новой детекции: сетка перестала быть парой `bpm`/`first_beat_frame` и стала списком сегментов.

- **`dj_domain::BeatGrid`** — сегменты `BeatSegment { frame, beat, bpm }`: доля `N` стоит на кадре
  `frame + (N − beat) · 60/bpm · rate`. Вопросы задаются сетке: `beat_at(frame)`, `frame_of_beat(beat)`,
  `bpm_at(frame)`. Сетка валидируется: кадры и доли строго растут, темп конечный и положительный; иначе
  `None`, а не «сетка, которая врёт».
- **Один темп — один сегмент.** Для всех сегодняшних треков снаружи ничего не изменилось: числа те же.
- **Доли продолжаются через стык.** Разрез на новом темпе — это прыжок кадра доли, а не вторая сетка с
  нуля: иначе номера тактов после разреза неверны.
- **Файл остался совместимым:** в `.djmeta` первый сегмент пишется как `bpm`/`first_beat_frame`,
  остальные — как `anchors` (формат уже был такой). Старый файл без якорей читается как одна сетка.
- **В снапшоте — темп у плейхеда:** `beat` (доля, дробная) и `local_bpm`, плюс `source_rate` — сетка
  живёт в кадрах файла, и 44,1 кГц трек в 48 кГц движке считается по своим кадрам. Подпись деки берёт
  `local_bpm`, поэтому на треке с меняющимся темпом она следует за головой, а не врёт про весь файл.

Проверки: `crates/dj-domain/tests/grid.rs` (арифметика, стык, отказы, чтение из файла),
`the_published_tempo_and_beat_follow_the_play_head` (снапшот меняет темп на стыке, доля идёт 8 → 9),
`a_grid_is_read_in_the_track_own_rate_not_the_engine_one` (44,1 кГц: одна секунда = 2 доли, а не 1,84 —
контрольная рука на чтение темпа движка вместо темпа файла). На реальном файле 44,1 кГц подпись осталась
верной.

**Что осталось из этой темы:** разрезать голоса окон по времени, а не только по темпу (резкая смена —
шаг 2); плавный дрейф — слежение за фазой, задача `DJP-SYNC-002` (шаг 4); редактор сетки (шаг 3) теперь
опирается на ту же модель.

## Чего детектор пока не умеет — записано честно"""
