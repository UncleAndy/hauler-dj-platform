#!/usr/bin/env bash
# Regenerates the committed media fixtures. The content is our own synthesised sine — no
# third-party material — so the fixtures can live in the repository (DJP-LIC-006).
#
# Tools are used as build-time utilities only: they are not linked into the app.
#   nix shell nixpkgs#python3 nixpkgs#flac nixpkgs#lame nixpkgs#vorbis-tools -c bash scripts/gen-media-fixtures.sh
set -euo pipefail
cd "$(dirname "$0")/.."
out="crates/dj-codec/tests/fixtures/audio"
mkdir -p "$out"

python3 - "$out" <<'PY'
import math, struct, sys, wave, pathlib

out = pathlib.Path(sys.argv[1])
rate = 44100

def write(path, seconds, tone_from):
    frames = int(rate * seconds)
    with wave.open(str(path), "wb") as w:
        w.setnchannels(2)
        w.setsampwidth(2)
        w.setframerate(rate)
        data = bytearray()
        for n in range(frames):
            value = 0.0
            if n >= tone_from:
                value = 0.6 * math.sin(2.0 * math.pi * 440.0 * n / rate)
            sample = int(max(-1.0, min(1.0, value)) * 32000)
            data += struct.pack("<hh", sample, sample)
        w.writeframes(bytes(data))

write(out / "tone-1s-44100.wav", 1.0, 0)
write(out / "silence-then-tone-2s-44100.wav", 2.0, rate)
print("wav written")
PY

flac -s -f -o "$out/tone-1s-44100.flac" "$out/tone-1s-44100.wav"
flac -s -f -o "$out/silence-then-tone-2s-44100.flac" "$out/silence-then-tone-2s-44100.wav"
lame --quiet -b 320 "$out/tone-1s-44100.wav" "$out/tone-1s-44100-cbr.mp3"
lame --quiet -V 2 "$out/tone-1s-44100.wav" "$out/tone-1s-44100-vbr.mp3"
oggenc --quiet -q 5 -o "$out/tone-1s-44100.ogg" "$out/tone-1s-44100.wav"

# The WAVs are regenerated by the tests themselves; only the encoded fixtures are committed.
rm -f "$out"/*.wav
ls -l "$out"
